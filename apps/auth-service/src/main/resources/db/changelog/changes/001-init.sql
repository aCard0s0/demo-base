-- The schema as Hibernate's ddl-auto=update built it before Liquibase took over. A database that already has
-- these tables has this changeset marked ran rather than run again.
--changeset auth-service:1-init
--preconditions onFail:MARK_RAN
--precondition-sql-check expectedResult:0 SELECT count(*) FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = 'users'
create table users (
    id             bigint generated by default as identity primary key,
    email          varchar(255) not null unique,
    name           varchar(255) not null,
    password_hash  varchar(255) not null,
    role           varchar(20)  not null default 'USER' check (role in ('ADMIN', 'MODERATOR', 'USER')),
    suspended      boolean      not null default false,
    token_version  integer      not null default 0
);

-- One row per agent whose tokens have ever been revoked; no row is version zero.
create table agent_token_versions (
    agent_id bigint  primary key,
    version  integer not null default 0
);
